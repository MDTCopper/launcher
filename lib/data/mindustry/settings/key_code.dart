final Map<int, MindustryKeyCode> _keyCodesByOrdinal = {
  for (final code in mindustryKeyCodes) code.ordinal: code,
};

final Map<String, MindustryKeyCode> _keyCodesByName = {
  for (final code in mindustryKeyCodes) code.name: code,
};

/// 按 settings.bin 里存的序号取键码；不认识的序号返回 null
MindustryKeyCode? mindustryKeyCodeOf(int ordinal) =>
    _keyCodesByOrdinal[ordinal];

/// 按 arc 枚举名取键码（键位表的默认键走这里）；不认识的名字返回 null
MindustryKeyCode? mindustryKeyCodeNamed(String name) => _keyCodesByName[name];
